"""Opt-in integration test: spends real Sarvam API credits; never mocks responses.

Run from bolicad: ../.venv/bin/python tests/live_smoke.py
"""
import base64
import json
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from ai_service import load_key, make_client, transcribe, understand
from geometry import build_mesh, export_stl


def main():
    client = make_client(load_key())
    report = {}
    bracket = understand(client, "Make an L bracket 80 mm tall, 50 mm wide, 40 mm deep, 4 mm thick, with two 5 mm holes on the upright.")
    assert bracket.shape_type == "bracket"
    for k, v in dict(height=80,width=50,depth=40,thickness=4,hole_count=2,hole_diameter=5).items():
        assert bracket.dimensions[k] == v, (k, bracket.dimensions)
    mesh = build_mesh(bracket)
    assert len(export_stl(mesh)) > 84
    report["english_bracket"] = "PASS"
    taller = understand(client, "Make the bracket 120 mm tall; keep everything else the same.", bracket)
    assert taller.dimensions["height"] == 120
    for k in bracket.dimensions:
        if k != "height":
            assert taller.dimensions[k] == bracket.dimensions[k], (k, taller.dimensions)
    assert build_mesh(taller).extents[2] == 120
    report["contextual_edit"] = "PASS"
    for command, shape in [
        ("Make a rectangular mounting plate 100 mm long, 60 mm wide, thickness 4 mm and four 5 mm holes.","plate"),
        ("Make an open-top box length 100 mm, width 70 mm, height 50 mm, wall thickness 3 mm.","box"),
    ]:
        spec = understand(client, command)
        assert spec.shape_type == shape
        export_stl(build_mesh(spec))
        report[shape] = "PASS"
    try:
        understand(client, "Make an open-top box length 10 mm, width 10 mm, height 10 mm, wall thickness 8 mm.")
    except Exception as exc:
        from ai_service import ServiceError
        assert isinstance(exc, ServiceError)
        report["invalid_dimensions"] = "PASS"
    else:
        raise AssertionError("AI silently changed impossible dimensions")
    # Synthetic fixture generated by the real Bulbul service, then recognized by
    # the real Saaras v4 service. This is not a physical microphone test.
    speech = client.text_to_speech.convert(
        text="मला ऐंशी मिलीमीटर उंच, पन्नास मिलीमीटर रुंद आणि चाळीस मिलीमीटर खोल एल आकाराचा ब्रॅकेट बनव. त्याची जाडी चार मिलीमीटर ठेव आणि त्यात पाच मिलीमीटर व्यासाची दोन छिद्रे ठेव.",
        model="bulbul:v4-flash", language_code="mr-IN", speaker="ishita_mr_conversational", output_audio_codec="wav",
        request_options={"max_retries":0,"timeout_in_seconds":55})
    audio = base64.b64decode(speech.audios[0])
    transcript = transcribe(client, audio, "mr-IN")
    spec = understand(client, transcript)
    assert spec.shape_type == "bracket", spec
    for k, v in dict(height=80,width=50,depth=40,thickness=4,hole_count=2,hole_diameter=5).items():
        assert spec.dimensions[k] == v, (k, transcript, spec.dimensions)
    export_stl(build_mesh(spec))
    report["marathi_synthetic_voice_roundtrip"] = "PASS"
    report["marathi_transcript"] = transcript
    # Optional local-only fixture for browser microphone capture testing.
    (Path(tempfile.gettempdir()) / "bolicad-marathi-command.wav").write_bytes(audio)
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
